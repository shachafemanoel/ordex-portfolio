export function translateUI(key: string, opts?: TranslateOptions): string {
  const locale = opts?.locale ?? 'he';
  const entry = UI_TRANSLATIONS[key];
  const raw = entry ? entry[locale] ?? entry.he : opts?.fallback ?? key;

  if (!opts?.params) return raw;

  return Object.entries(opts.params).reduce((acc, [paramKey, paramValue]) => {
    return acc.replaceAll(`{${paramKey}}`, String(paramValue));
  }, raw);
}
