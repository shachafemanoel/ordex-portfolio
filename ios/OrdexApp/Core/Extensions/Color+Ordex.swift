import SwiftUI

extension Color {
    static let ordexBlue = Color(hex: "#1d4ed8")
    static let ordexGreen = Color(hex: "#047857")
    static let ordexEmerald = Color(hex: "#10b981")
    static let ordexAmber = Color(hex: "#b45309")
    static let ordexRed = Color(hex: "#b91c1c")
    static let ordexGray = Color(hex: "#475569")
    static let ordexBackground = Color(UIColor.systemGroupedBackground)
    static let ordexSurface = Color(UIColor.secondarySystemGroupedBackground)

    init(hex: String) {
        let hex = hex.trimmingCharacters(in: CharacterSet.alphanumerics.inverted)
        var int: UInt64 = 0
        Scanner(string: hex).scanHexInt64(&int)
        let a, r, g, b: UInt64
        switch hex.count {
        case 3: // RGB (12-bit)
            (a, r, g, b) = (255, (int >> 8) * 17, (int >> 4 & 0xF) * 17, (int & 0xF) * 17)
        case 6: // RGB (24-bit)
            (a, r, g, b) = (255, int >> 16, int >> 8 & 0xFF, int & 0xFF)
        case 8: // ARGB (32-bit)
            (a, r, g, b) = (int >> 24, int >> 16 & 0xFF, int >> 8 & 0xFF, int & 0xFF)
        default:
            (a, r, g, b) = (255, 0, 0, 0)
        }

        self.init(
            .sRGB,
            red: Double(r) / 255,
            green: Double(g) / 255,
            blue: Double(b) / 255,
            opacity: Double(a) / 255
        )
    }
}

